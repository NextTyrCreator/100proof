import type { RoomShard } from "../lib/inventory";
import { proofLedger } from "../lib/proof-ledger";
import { readTwiceSummary } from "../lib/read-twice";
import type { ScanStats } from "../lib/scan-stats";

/**
 * RESEARCH ONLY. Demo-prep comparison cards: for each feature beat, the same walk without the step and
 * with it. The "without" side is what that step's absence produces on this walk by construction (a total
 * with no evidence, one read, no merge, one check at the end). It is not a measurement of any other
 * product, and no card names one. The cards are written to `docs/research/DEMO_COMPARE.md`; the app never
 * shows them.
 */
type DemoCard = {
  beat: string;
  without: { label: string; value: string };
  with: { label: string; value: string };
  note: string;
};

function money(value: number) {
  return `$${Math.round(value).toLocaleString("en-US")}`;
}

export function demoCards(rooms: RoomShard[], stats: ScanStats | null): DemoCard[] {
  const ledger = proofLedger(rooms);
  const reads = readTwiceSummary(rooms);
  const lines = rooms.reduce((sum, room) => sum + room.items.filter((item) => !item.hidden).length, 0);
  const listed = stats?.listedLines ?? lines;
  const merged = (stats?.mergedLive ?? 0) + (stats?.mergedAtDone ?? 0) + (stats?.repeatsMergedByOwner ?? 0);
  const acrossRooms = rooms.reduce((sum, room) => sum + room.items.filter((item) => /Also seen in /.test(item.detail)).length, 0);
  const live = (stats?.mergedLive ?? 0) + (stats?.repeatsAsked ?? 0);
  return [
    {
      beat: "Proof ledger (14.2)",
      without: { label: "A total with no evidence", value: `${money(ledger.total)}, one number` },
      with: {
        label: "Proof ledger",
        value: `${money(ledger.proven)} proven · ${money(ledger.bands.estimated.usd)} estimated · ${money(ledger.bands.stated.usd)} stated`,
      },
      note: "Proven is receipt confirmed plus seen and identified. It describes evidence, not what a policy pays.",
    },
    {
      beat: "Read twice (14.1)",
      without: { label: "One read", value: `${reads.read} high-value lines, each on one answer, none flagged` },
      with: { label: "Read twice", value: `${reads.agreed} agreed · ${reads.unsure} flagged unsure, both reads shown` },
      note: "A disagreement is shown only if this walk produced one. Never staged.",
    },
    {
      beat: "One object, one line (5.2)",
      without: { label: "Each clip's list kept as is", value: `${listed} lines` },
      with: { label: "Repeats merged", value: `${lines} lines · ${merged} merged · ${acrossRooms} seen in two rooms` },
      note: "Merged counts strong matches and the owner's Same item answers.",
    },
    {
      beat: "Repeats while filming",
      without: { label: "Checked once, at the end", value: "0 found while filming" },
      with: { label: "Checked after every clip", value: `${live} found while filming (${stats?.mergedLive ?? 0} merged on the spot)` },
      note: "Counts from this scan's own record.",
    },
  ];
}

export function demoCompareMarkdown(cards: DemoCard[], run: number | null) {
  return [
    "# Demo comparison cards",
    "",
    `Research only. Generated by \`corepack pnpm --filter @100proof/web metrics add\`${run ? ` for Run ${String(run).padStart(2, "0")}` : ""}. Do not edit by hand. These numbers are for demo preparation and an overlay in the video. They are never shown in the app.`,
    "",
    "Each card is the same walk without the step and with it. The left side is what the step's absence produces on this walk. It is not a measurement of any other product.",
    "",
    ...cards.flatMap((card) => [
      `## ${card.beat}`,
      "",
      `| ${card.without.label} | ${card.with.label} |`,
      "| --- | --- |",
      `| ${card.without.value} | ${card.with.value} |`,
      "",
      card.note,
      "",
    ]),
  ].join("\n");
}
